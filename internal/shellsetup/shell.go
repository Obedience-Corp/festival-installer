package shellsetup

import (
	"fmt"
	"path/filepath"
	"strings"
)

func Supported(shell string) bool {
	switch shell {
	case "bash", "zsh", "fish", "powershell", "pwsh":
		return true
	}
	return false
}

func Quote(shell, value string) string {
	if shell == "pwsh" || shell == "powershell" {
		return "'" + strings.ReplaceAll(value, "'", "''") + "'"
	}
	return "'" + strings.ReplaceAll(value, "'", "'\\''") + "'"
}

// Source is deliberately independent of PATH and the installer's executable
// location: a desktop sidecar may be replaced with every app update.
func Source(shell, file string) string {
	q := Quote(shell, file)
	switch shell {
	case "fish":
		return fmt.Sprintf("if status is-interactive; and test -r %s\n  source %s\nend\n", q, q)
	case "pwsh", "powershell":
		return fmt.Sprintf("if (Test-Path -LiteralPath %s) { . %s }\n", q, q)
	default:
		return fmt.Sprintf("case $- in *i*) [ ! -r %s ] || . %s ;; esac\n", q, q)
	}
}

// Header makes tool resolution deterministic without duplicate PATH entries.
// It runs before tool-generated code, whose command lookups use these paths.
func Header(shell string, tools []string) string {
	var b strings.Builder
	b.WriteString("# Generated by Festival setup; refreshed on install, update and repair.\n")
	if shell == "zsh" {
		// Older supported fest helpers register Bash completions in Zsh.
		// Establish completion without prompting or writing a compdump during
		// read-only verification. Respect a user's existing completion setup.
		b.WriteString("if (( ! $+functions[compdef] )); then autoload -Uz compinit; compinit -i -D; fi\n")
		b.WriteString("if (( ! $+functions[complete] )); then autoload -Uz bashcompinit; bashcompinit; fi\n")
	}
	if shell == "bash" || shell == "zsh" {
		b.WriteString(`__festival_prepend_path() {
  __festival_rest=$PATH
  __festival_result=$1
  while :; do
    case $__festival_rest in
      *:*) __festival_part=${__festival_rest%%:*}; __festival_rest=${__festival_rest#*:}; __festival_more=1 ;;
      *) __festival_part=$__festival_rest; __festival_more=0 ;;
    esac
    if [ "$__festival_part" != "$1" ]; then __festival_result=$__festival_result:$__festival_part; fi
    [ "$__festival_more" = 1 ] || break
  done
  export PATH=$__festival_result
  unset __festival_rest __festival_result __festival_part __festival_more
}
`)
	}
	seen := map[string]bool{}
	for i := len(tools) - 1; i >= 0; i-- {
		dir := filepath.Dir(tools[i])
		if seen[dir] {
			continue
		}
		seen[dir] = true
		q := Quote(shell, dir)
		switch shell {
		case "fish":
			fmt.Fprintf(&b, "fish_add_path --prepend --global %s\n", q)
		case "pwsh", "powershell":
			fmt.Fprintf(&b, "$env:PATH = %s + [IO.Path]::PathSeparator + (($env:PATH -split [IO.Path]::PathSeparator | Where-Object { $_ -ne %s }) -join [IO.Path]::PathSeparator)\n", q, q)
		default:
			fmt.Fprintf(&b, "__festival_prepend_path %s\n", q)
		}
	}
	if shell == "bash" || shell == "zsh" {
		b.WriteString("unset -f __festival_prepend_path\n")
	}
	return b.String()
}

// Probe runs after the shell's actual startup files, so a stale block, early
// return, or conflicting alias cannot masquerade as a ready installation.
func Probe(shell string, wrap bool) string {
	return ProbeHelpers(shell, []string{"cgo", "fgo"}, wrap)
}

func ProbeHelpers(shell string, helpers []string, wrap bool) string {
	var b strings.Builder
	names := append([]string(nil), helpers...)
	if wrap {
		names = append(names, "grok", "claude", "codex")
	}
	for _, name := range names {
		isProvider := name != "cgo" && name != "fgo"
		switch shell {
		case "fish":
			fmt.Fprintf(&b, "functions -q %s; or exit 21\n", name)
			if isProvider {
				fmt.Fprintf(&b, "string match -q '*obey wrap*' -- (functions %s | string collect); or exit 22\n", name)
			}
		case "powershell", "pwsh":
			fmt.Fprintf(&b, "if (-not (Get-Command %s -CommandType Function -ErrorAction SilentlyContinue)) { exit 21 }\n", name)
		default:
			fmt.Fprintf(&b, "typeset -f %s >/dev/null || exit 21\n", name)
			if isProvider {
				fmt.Fprintf(&b, "alias %s >/dev/null 2>&1 && exit 22\ncase \"$(typeset -f %s)\" in *'obey wrap'*) ;; *) exit 22 ;; esac\n", name, name)
			}
		}
	}
	b.WriteString("echo FESTIVAL_INTEGRATION_READY\n")
	return b.String()
}
