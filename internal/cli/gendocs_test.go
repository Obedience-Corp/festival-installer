func TestGendocs_RemovesStaleFiles(t *testing.T) {
	outDir := t.TempDir()

	stale := filepath.Join(outDir, "festival_removed-command.md")
	if err := os.WriteFile(stale, []byte("stale\n"), 0o644); err != nil {
		t.Fatalf("write stale file: %v", err)
	}

	_, _, err := runGendocs(t, "--output", outDir, "--format", "markdown")
	if err != nil {
		t.Fatalf("gendocs markdown: %v", err)
	}

	if _, err := os.Stat(stale); !os.IsNotExist(err) {
		t.Fatalf("expected stale generated file to be removed, stat err = %v", err)
	}
}

func TestGendocs_HiddenFromHelp(t *testing.T) {
	root := newGendocsRoot()
	var out bytes.Buffer
	root.SetOut(&out)
	root.SetArgs([]string{"--help"})
	if err := root.Execute(); err != nil {
		t.Fatalf("festival --help: %v", err)
	}
	if strings.Contains(out.String(), "gendocs") {
		t.Fatalf("expected gendocs to be hidden from help output, got:\n%s", out.String())
	}
}

func TestGendocs_DefaultOutputDir(t *testing.T) {
	cwd, err := os.Getwd()
	if err != nil {
		t.Fatalf("getwd: %v", err)
	}
	t.Cleanup(func() {
		if err := os.Chdir(cwd); err != nil {
			t.Fatalf("restore cwd: %v", err)
		}
	})
	if err := os.Chdir(t.TempDir()); err != nil {
		t.Fatalf("chdir: %v", err)
	}

	if _, _, err := runGendocs(t); err != nil {
		t.Fatalf("gendocs with default flags: %v", err)
	}

	if _, err := os.Stat(filepath.Join("docs", "festival_version.md")); err != nil {
		t.Fatalf("expected default output dir docs/ to contain generated files: %v", err)
	}
}

