package cli_test

import (
	"bytes"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/spf13/cobra"

	"github.com/Obedience-Corp/festival-installer/internal/cli"
)

func newGendocsRoot() *cobra.Command {
	root := &cobra.Command{Use: "festival", SilenceErrors: true, SilenceUsage: true}
	root.AddCommand(cli.NewVersionCommand(testFestivalVersion))
	root.AddCommand(cli.NewWhichCommand())
	root.AddCommand(cli.NewGendocsCommand())
	return root
}

func runGendocs(t *testing.T, args ...string) (string, string, error) {
	t.Helper()
	root := newGendocsRoot()
	var out, errOut bytes.Buffer
	root.SetOut(&out)
	root.SetErr(&errOut)
	root.SetArgs(append([]string{"gendocs"}, args...))
	err := root.Execute()
	return out.String(), errOut.String(), err
}

func TestGendocs_Markdown(t *testing.T) {
	outDir := t.TempDir()

	_, _, err := runGendocs(t, "--output", outDir, "--format", "markdown")
	if err != nil {
		t.Fatalf("gendocs markdown: %v", err)
	}

	wantFiles := []string{"festival.md", "festival_version.md", "festival_which.md"}
	for _, name := range wantFiles {
		path := filepath.Join(outDir, name)
		if _, err := os.Stat(path); err != nil {
			t.Fatalf("expected generated file %s: %v", name, err)
		}
	}

	data, err := os.ReadFile(filepath.Join(outDir, "festival_version.md"))
	if err != nil {
		t.Fatalf("read festival_version.md: %v", err)
	}
	content := string(data)

	if strings.Contains(content, "Auto generated by spf13/cobra") {
		t.Fatalf("expected no AutoGenTag footer, got:\n%s", content)
	}

	if strings.HasSuffix(content, "\n\n") {
		t.Fatalf("expected no trailing blank line, got trailing bytes %q", content[len(content)-10:])
	}
	if !strings.HasSuffix(content, "\n") {
		t.Fatalf("expected file to end with exactly one newline, got %q", content[len(content)-10:])
	}
}

